pub struct Longhand {
    pub name: &'static str,
    pub value: &'static str,
    pub inherited: bool,
    pub initial: &'static str,
}

pub struct KeywordType {
    pub name: &'static str,
    pub keywords: &'static [&'static str],
}

pub enum ShorthandKind {
    FourSides,
    Pair,
    AnyOrder,
    Custom,
}

pub struct Shorthand {
    pub name: &'static str,
    pub longhands: &'static [&'static str],
    pub kind: ShorthandKind,
}

const fn l(name: &'static str, value: &'static str, inherited: bool, initial: &'static str) -> Longhand {
    Longhand { name, value, inherited, initial }
}

const fn k(name: &'static str, keywords: &'static [&'static str]) -> KeywordType {
    KeywordType { name, keywords }
}

const fn s(name: &'static str, kind: ShorthandKind, longhands: &'static [&'static str]) -> Shorthand {
    Shorthand { name, longhands, kind }
}

